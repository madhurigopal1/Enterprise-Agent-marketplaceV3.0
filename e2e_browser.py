import asyncio, os
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path=os.getenv("CHROME_PATH")) if os.getenv("CHROME_PATH") else await p.chromium.launch()
        ctx = await b.new_context(viewport={"width":1366,"height":900}, accept_downloads=True); pg = await ctx.new_page()
        errs=[]; pg.on("pageerror", lambda e: errs.append(str(e))); pg.on("console", lambda m: m.type=="error" and errs.append(m.text))
        replies = iter(["Looks fine", "Need source docs", "Incident review"])
        pg.on("dialog", lambda d: asyncio.ensure_future(d.accept(next(replies, "ok"))))
        await pg.goto("http://127.0.0.1:8000/"); await pg.wait_for_timeout(1000)
        print("TABS", await pg.locator(".tabs button").all_inner_texts())
        await pg.select_option("#user","arjun"); await pg.wait_for_timeout(700)
        for _ in range(2):
            await pg.select_option("#sample", label="Finance review (needs approval)"); await pg.click("#run"); await pg.wait_for_timeout(800)
        await pg.click("#tab-approvals"); await pg.wait_for_timeout(800)
        print("CARDS", await pg.locator("#approvalsList .card").count())
        await pg.check("#selectAll"); print("BULK BTN", await pg.inner_text("#bulkApprove"))
        await pg.screenshot(path="shot_bulk.png")
        await pg.click("#bulkApprove"); await pg.wait_for_timeout(1200)
        print("AFTER BULK", await pg.locator("#approvalsList .card").count())
        await pg.click("#tab-runs"); await pg.wait_for_timeout(800)
        print("RUN ROWS", await pg.locator("#runsList tbody tr").count())
        await pg.screenshot(path="shot_runs.png")
        await pg.locator("#runsList button").first.click(); await pg.wait_for_timeout(900)
        stars = pg.locator(".stars button"); print("STAR BTNS", await stars.count())
        await stars.nth(3).click(); await pg.wait_for_timeout(500)
        async with pg.expect_download() as d: await pg.click("text=Download report (.md)")
        print("REPORT", (await d.value).suggested_filename)
        await pg.screenshot(path="shot_run.png", full_page=True)
        await pg.select_option("#user","sam"); await pg.wait_for_timeout(800)
        await pg.click("#tab-market"); await pg.wait_for_timeout(800)
        await pg.locator("#agents .card", has_text="Documentation Agent").locator("button").click(); await pg.wait_for_timeout(800)
        await pg.click("text=Kill switch: suspend"); await pg.wait_for_timeout(900)
        print("SUSPENDED BADGE", await pg.locator("#agentDetail .badge", has_text="suspended").count())
        await pg.screenshot(path="shot_kill.png")
        await pg.click("#tab-governance"); await pg.wait_for_timeout(800)
        async with pg.expect_download() as d: await pg.click("#auditExport")
        print("CSV", (await d.value).suggested_filename)
        print("ERRORS", errs); await b.close()
asyncio.run(main())
